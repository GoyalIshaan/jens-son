// QKV uses an fp16 row scale rounded from amax/127 and an fp32 reciprocal
// of that stored scale. This scalar path executes once per row.
module vec_kv_scale(input wire [30:0] amax,output reg [15:0] scale,output reg [31:0] reciprocal);
    reg [23:0] mant, sig;
    reg [31:0] numerator;
    reg [24:0] quotient;
    reg [7:0] remainder;
    integer exponent,shift,he,leading,i;
    reg [23:0] half_int;
    reg guard_bit,sticky;
    reg [23:0] den;
    reg [47:0] inv_n,inv_q,inv_r;
    always @* begin
        scale=0;reciprocal=0;
        mant={1'b1,amax[22:0]};
        // A 24-bit significand divided by 127 needs a 6- or 7-bit renormalization.
        shift=mant>=24'hfe0000 ? 6 : 7;
        exponent=$signed({1'b0,amax[30:23]})-127-shift;
        numerator={8'd0,mant}<<shift;
        quotient=numerator/127;remainder=numerator%127;
        if(remainder>=64) quotient=quotient+1'b1;
        if(quotient[24]) begin sig=quotient[24:1];exponent=exponent+1;end
        else sig=quotient[23:0];
        // Round the fp32 result to half, including subnormals.
        he=exponent+15;shift=he<=0 ? 14-he : 13;
        half_int=0;guard_bit=0;sticky=0;
        if(shift<=24) begin
            half_int=sig>>shift;
            guard_bit=sig[shift-1];
            sticky=|(sig & ((24'd1<<(shift-1))-1'b1));
            if(guard_bit && (sticky || half_int[0])) half_int=half_int+1'b1;
        end
        if(amax[30:23]!=0) begin
            if(he>=31) scale=16'h7c00;
            else if(he<=0) scale=half_int[10:0];
            else scale={1'b0,he[4:0],10'd0}+half_int[9:0]+(half_int[11] ? 16'h400 : 0);
        end
        // Normalize the stored half, then divide a power of two by its
        // eleven-bit significand. Round once to nearest fp32, ties to even.
        den={13'd0,|scale[14:10],scale[9:0]};
        leading=0;
        for(i=0;i<11;i=i+1) if(den[i]) leading=i;
        exponent=scale[14:10]!=0 ? $signed({1'b0,scale[14:10]})-15 : leading-24;
        den=den<<(10-leading);
        inv_n=48'd1<<34;inv_q=0;inv_r=0;
        if(scale[14:0]!=0 && scale[14:10]!=31) begin
            inv_q=inv_n/den;inv_r=inv_n%den;
            if((inv_r<<1)>den || ((inv_r<<1)==den && inv_q[0])) inv_q=inv_q+1;
            he=126-exponent;
            if(inv_q[24]) begin inv_q=inv_q>>1;he=he+1;end
            reciprocal={1'b0,he[7:0],inv_q[22:0]};
        end
    end
endmodule

// Finite fp32 -> signed int8, round-to-nearest even and saturate to +/-127.
module vec_round_i8(input wire [31:0] x,output wire [7:0] code);
    wire [7:0] exponent=x[30:23];
    wire [23:0] mant={1'b1,x[22:0]};
    wire [4:0] dist_bits=8'd150-exponent;
    wire [7:0] mag=mant>>dist_bits;
    wire guard_bit=mant[(dist_bits-1'b1) & 31];
    wire sticky=|(mant & ((24'd1<<(dist_bits-1'b1))-1'b1));
    wire [7:0] rounded=mag+(guard_bit && (sticky || mag[0]));
    wire [7:0] clipped=exponent<126 ? 0 : exponent>=134 || rounded>127 ? 127 : rounded;
    assign code=x[31] ? -clipped : clipped;
endmodule

// Byte-addressed SRAM returns a zero-extended 8-, 16- or 32-bit word.
// Type tags are internal to the decoded descriptor port of vec_unit.
module vec_unpack(input wire [31:0] raw,input wire [2:0] dtype,
                  input wire exponent_value,raw_token,output reg [31:0] value);
    integer i,lead,biased;
    reg [23:0] mant;
    reg [7:0] mag;
    reg [32:0] rounded;
    integer shift;
    always @* begin
        lead=0;biased=0;mant=0;mag=0;value=raw;rounded=0;shift=0;
        case(dtype)
            1: begin // fp16
                if(raw[14:10]==31) value={raw[15],8'hff,raw[9:0],13'd0};
                else if(raw[14:10]!=0) value={raw[15],8'd112+{3'd0,raw[14:10]},raw[9:0],13'd0};
                else if(raw[9:0]==0) value={raw[15],31'd0};
                else begin
                    for(i=0;i<10;i=i+1) if(raw[i]) lead=i;
                    biased=103+lead;mant={14'd0,raw[9:0]}<<(23-lead);
                    value={raw[15],biased[7:0],mant[22:0]};
                end
            end
            3: if (!raw_token && raw!=0) begin // Unsigned integer to fp32, ties to even.
                for(i=0;i<32;i=i+1) if(raw[i]) lead=i;
                biased=127+lead;
                if(lead<=23) mant=raw<<(23-lead);
                else begin
                    shift=lead-23;
                    rounded=raw>>shift;
                    if(raw[shift-1] && (rounded[0] || |(raw & ((32'd1<<(shift-1))-1'b1))))
                        rounded=rounded+1'b1;
                    if(rounded[24]) begin biased=biased+1;rounded=rounded>>1;end
                    mant=rounded[23:0];
                end
                value={1'b0,biased[7:0],mant[22:0]};
            end
            2,4: begin
                if(dtype==4 && exponent_value) begin
                    biased=127+$signed(raw[7:0]);
                    value=biased>0 ? {1'b0,biased[7:0],23'd0} :
                          (biased==0 ? 32'h00400000 : 32'h00200000);
                end else begin
                    mag=raw[7] ? -raw[7:0] : raw[7:0];
                    for(i=0;i<8;i=i+1) if(mag[i]) lead=i;
                    biased=127+lead;mant={16'd0,mag}<<(23-lead);
                    value=mag==0 ? 0 : {raw[7],biased[7:0],mant[22:0]};
                end
            end
        endcase
    end
endmodule

module vec_pack(input wire [31:0] value,input wire [2:0] dtype,input wire raw,
                output reg [31:0] packed_value);
    wire [7:0] i8;
    vec_round_i8 round_code(value,i8);
    integer e,shift;
    reg [23:0] mant,rounded;
    reg guard_bit,sticky;
    always @* begin
        packed_value=value;
        mant={1'b1,value[22:0]};e=$signed({1'b0,value[30:23]})-112;
        shift=e<=0 ? 14-e : 13;rounded=0;guard_bit=0;sticky=0;
        if(!raw) case(dtype)
            1: begin
                if(shift<=24) begin
                    rounded=mant>>shift;guard_bit=mant[shift-1];
                    sticky=|(mant & ((24'd1<<(shift-1))-1'b1));
                    rounded=rounded+(guard_bit && (sticky || rounded[0]));
                end
                packed_value={16'd0,value[31],15'd0};
                if(value[30:23]==255 && value[22:0]!=0) packed_value=32'h7e00;
                else if(e>=31) packed_value[14:0]=15'h7c00;
                else if(e<=0) packed_value[14:0]=rounded;
                else packed_value[14:0]={e[4:0],10'd0}+rounded[9:0]+(rounded[11] ? 15'h400 : 0);
            end
            2: packed_value={24'd0,i8};
            3,4: begin // Integer stores truncate toward zero. Keep the addressed low bits.
                shift=$signed({1'b0,value[30:23]})-150;
                packed_value=shift>=0 ? {8'b0,mant}<<shift : mant>>(-shift);
                if(value[31]) packed_value=-packed_value;
            end
        endcase
    end
endmodule

