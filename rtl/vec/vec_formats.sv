//      for every X here (N = 24-bit significand << 6 or 7; checked over all 2^23 significands)
//   2  the fp16 scale (the same double rounding as the reference: to a 24-bit quotient, then to half)
//   3  the exact fp32 reciprocal: the fp16 significand has 11 bits, so a 1,024-entry table holds 2^34 / den
