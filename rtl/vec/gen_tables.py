"""Generate sfu_tables.vh (the special-function unit's ROMs, bit-identical to golden/chip_sfu.py's tables)
and the fma / lane test vectors in vec/ (expected results from golden/bitexact_vec.py).

    python3 rtl/vec/gen_tables.py
"""
import os
import sys

import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "golden"))
import bitexact_vec as BV  # noqa: E402
import chip_sfu as S  # noqa: E402


def bits(t):
    return [int(v) for v in t.float().contiguous().view(torch.int32).numpy().astype(np.uint32)]


def rom(name, vals, abits):
    lines = [f"function [31:0] {name};", f"    input [{abits - 1}:0] i;", "    begin", "        case (i)"]
    for k, v in enumerate(vals):
        lines.append(f"            {abits}'d{k}: {name} = 32'h{v:08x};")
    lines += ["            default: " + name + " = 32'h0;", "        endcase", "    end", "endfunction", ""]
    return "\n".join(lines)


def tables():
    out = ["// Generated by gen_tables.py from golden/chip_sfu.py. Do not edit.", ""]
    out.append(rom("t_exp2", bits(S._tab("exp2", "cpu")), 6))
    out.append(rom("t_recip", bits(S._tab("recip", "cpu")), 8))
    out.append(rom("t_rsqrt", bits(S._tab("rsqrt", "cpu")), 8))
    lg = S._tab("log2", "cpu")
    for j in range(3):
        out.append(rom(f"t_log2_{j}", bits(lg[j]), 6))
    consts = dict(LOG2E=bits(torch.tensor([S.LOG2E]))[0], LN2=bits(torch.tensor([S.LN2]))[0])
    out.append("\n".join(f"localparam [31:0] C_{k} = 32'h{v:08x};" for k, v in consts.items()))
    open(os.path.join(HERE, "sfu_tables.vh"), "w").write("\n".join(out) + "\n")


def h(v):
    return f"{v & 0xffffffff:08x}"


def fma_vectors(n=20000, seed=3):
    """a b c y lines. Mix: random magnitudes, near-cancellation, products near c, zeros, -inf, ties."""
    g = torch.Generator().manual_seed(seed)
    def rnd(k, spread):
        return torch.randn(k, generator=g) * torch.exp2(torch.randint(-spread, spread + 1, (k,), generator=g).float())
    a, b, c = rnd(n, 30), rnd(n, 30), rnd(n, 60)
    k = n // 4                                       # cancellation: c = -(a*b) rounded, nudged
    c[:k] = -(a[:k] * b[:k]) * (1 + torch.randint(-3, 4, (k,), generator=g).float() * 2.0 ** -23)
    c[k:2 * k] = rnd(k, 3)                            # comparable magnitudes
    a[2 * k:2 * k + 200] = 0.0
    c[2 * k + 200:2 * k + 400] = 0.0
    a[2 * k + 400:2 * k + 450] = float("-inf")
    c[2 * k + 450:2 * k + 500] = float("-inf")
    a[2 * k + 500:2 * k + 600] = 1.0                  # pure adds
    b[2 * k + 600:2 * k + 700] = 1.0
    tiny = (torch.rand(300, generator=g) + 1) * 2.0 ** -63      # products near the flush threshold
    a[2 * k + 700:2 * k + 1000] = tiny
    b[2 * k + 700:2 * k + 1000] = tiny * 0.7
    # inputs are normal or zero (the chip never makes subnormals)
    for t in (a, b, c):
        t[(t.abs() < 2.0 ** -126) & (t != 0)] = 0.0
        t[t.abs() > 3e38] = torch.sign(t[t.abs() > 3e38]) * 3e38
        t[2 * k + 400:2 * k + 500] = t[2 * k + 400:2 * k + 500]
    a[2 * k + 400:2 * k + 450] = float("-inf")
    c[2 * k + 450:2 * k + 500] = float("-inf")
    y = BV.fma(a, b, c)
    with open(os.path.join(HERE, "vec", "fma.hex"), "w") as fh:
        for i in range(n):
            fh.write(" ".join(h(bits(t[i:i + 1])[0]) for t in (a, b, c, y)) + "\n")


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "vec"), exist_ok=True)
    tables()
    fma_vectors()
    print("wrote sfu_tables.vh, vec/fma.hex")
