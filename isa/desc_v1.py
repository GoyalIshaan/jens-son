"""Binary descriptor encoding for ISA v1: one 64-byte (512-bit) word per descriptor in descriptor memory.

The ISA defined descriptors as dataclasses (isa_v1.Dma, Mm, Vec). This fixes their bits. Fields are packed
from bit 0 upward in the order of the layouts below. `python3 isa/desc_v1.py` regenerates
rtl/chip/desc_fields.vh, so the RTL decoders and this encoder share one definition.

Vec's op-specific parameters share one 96-bit union (`par`); each op uses its own sub-layout.
DN stores log2(lv / lqk) as kshift, so the hardware finds the key head with a shift.
"""
import math
import os
import struct

import isa_v1 as I

TYPES = ["f32", "f16", "i8", "u32", "e8"]
VOVR = {"": 0, "n": 1, "m": 2, "p": 3}
MOVR = {"": 0, "n_in": 1, "n_out": 2}

DMA = [("src", 36), ("dst", 36), ("n0", 24), ("n1", 24), ("n2", 24),
       ("s1_src", 32), ("s1_dst", 32), ("s2_src", 32), ("s2_dst", 32)]
MM = [("n_in", 20), ("n_out", 20), ("rows", 10), ("act", 23), ("act_stride", 20), ("exps", 23),
      ("exps_stride", 20), ("dst", 23), ("dst_stride", 20), ("wfmt", 1), ("seg4", 1), ("epi", 2), ("wsrc", 23),
      ("id_base", 32), ("tscale", 32), ("ovr", 2)]
OPND = [("base", 23), ("sn", 20), ("sm", 20), ("sp", 20), ("dt", 3), ("on", 1)]
VEC = ([("n", 16), ("m", 16), ("p", 16), ("ovr", 2)] +
       [(f"{o}_{f}", b) for o in ("d", "a", "b", "c") for f, b in OPND] + [("neg", 1), ("par", 96)])
# sub-layouts of par (bit offsets inside par)
PAR = {
    "QUANT": [("exp_bias", 10)],
    "ROPE": [("rot", 16)],
    "CAUSAL": [("step", 32), ("step_on", 1)],          # step_on = 0: FSim's default step of 1
    "CONV4": [("win_on", 1), ("window", 23)],
    "DN": [("T", 16), ("commit", 1), ("work", 23), ("heads_m1", 2), ("lv", 16), ("lqk", 16), ("kshift", 4)],
    "SMTILE": [("vs", 23), ("e_off", 23), ("e_stride", 23), ("mlb", 23)],
}
assert sum(b for _, b in DMA) <= 512 and sum(b for _, b in MM) <= 512 and sum(b for _, b in VEC) <= 512
assert all(sum(b for _, b in v) <= 96 for v in PAR.values())


def _pack(layout, vals):
    word, at = 0, 0
    for name, bits in layout:
        v = int(vals.get(name, 0))
        lo, hi = -(1 << (bits - 1)), (1 << bits) - 1
        assert lo <= v <= hi, f"{name}={v} does not fit {bits} bits"
        word |= (v & ((1 << bits) - 1)) << at
        at += bits
    return word


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def encode(d):
    """One descriptor -> a 512-bit integer."""
    if isinstance(d, I.Dma):
        return _pack(DMA, d.__dict__)
    if isinstance(d, I.Mm):
        v = dict(d.__dict__)
        v.update(wfmt=int(d.wfmt == "int8"), seg4=int(d.seg == 4), epi=["f32", "acc", "argmax"].index(d.epi),
                 tscale=f32_bits(d.tscale), ovr=MOVR[d.override])
        return _pack(MM, v)
    assert isinstance(d, I.Vec)
    v = dict(n=d.n, m=d.m, p=d.p, ovr=VOVR[d.override])
    for tag, o in zip("dabc", (d.dst, d.a, d.b, d.c)):
        o = o if o is not None else I.Opnd(0)
        v.update({f"{tag}_base": o.base, f"{tag}_sn": o.sn, f"{tag}_sm": o.sm, f"{tag}_sp": o.sp,
                  f"{tag}_dt": TYPES.index(o.dtype)})
    v.update(d_on=int(d.dst is not None), a_on=int(d.a is not None), b_on=int(d.b is not None),
             c_on=int(d.c is not None))
    par = dict(d.par)
    v["neg"] = int(par.get("neg", 0))
    p = {}
    if "exp_bias" in par:
        p.update(exp_bias=par["exp_bias"])
    sub = None
    if "rot" in par:
        sub = "ROPE"
    elif "step" in par:
        sub = "CAUSAL"
    elif "lv" in par:
        sub = "DN"
        ratio = par["lv"] // par.get("lqk", 1)
        assert ratio * par.get("lqk", 1) == par["lv"] and ratio & (ratio - 1) == 0, "lv / lqk must be a power of 2"
        p.update(T=par.get("T", 1), commit=par.get("commit_spec", 1), work=par.get("work", 0),
                 heads_m1=par.get("heads", 1) - 1, lv=par["lv"], lqk=par.get("lqk", 1), kshift=int(math.log2(ratio)))
    elif "mlb" in par:
        sub = "SMTILE"
        eo, es = par["e"]
        p.update(vs=par["vs"], e_off=eo, e_stride=es, mlb=par["mlb"])
    elif "window" in par:
        sub = "CONV4"
        p.update(win_on=1, window=par["window"])
    if sub == "ROPE":
        p.update(rot=par["rot"])
    if sub == "CAUSAL":
        p.update(step=par["step"], step_on=1)
    layout = PAR[sub] if sub else PAR["QUANT"]
    if sub and "exp_bias" in par:
        raise AssertionError("exp_bias only with QUANT")
    v["par"] = _pack(layout, p)
    return _pack(VEC, v)


def image(prog):
    """Descriptor memory: one 512-bit word per descriptor, as hex lines (most significant first)."""
    assert len(prog.descs) <= I.DMEM_DESCS
    return [f"{encode(d):0128x}" for d in prog.descs]


def imem(bundles):
    assert len(bundles) <= I.IMEM_BUNDLES
    return [f"{w:064x}" for w in I.encode(bundles)]


def verilog_header():
    out = ["// Generated by isa/desc_v1.py: bit offsets of descriptor fields (do not edit).",
           "`ifndef DESC_FIELDS_VH", "`define DESC_FIELDS_VH"]
    for tag, layout in (("DMA", DMA), ("MM", MM), ("VEC", VEC)):
        at = 0
        for name, bits in layout:
            out.append(f"`define {tag}_{name.upper()} {at} +: {bits}")
            at += bits
    for sub, layout in PAR.items():
        at = 0
        for name, bits in layout:
            out.append(f"`define PAR_{sub}_{name.upper()} {at} +: {bits}")
            at += bits
    out.append("`endif")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "chip", "desc_fields.vh")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(verilog_header())
    print("wrote", os.path.normpath(path))
